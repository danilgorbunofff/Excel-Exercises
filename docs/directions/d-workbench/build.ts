// Why this exists: writes direction D, "Workbench": the exercise screen in
// Spreadsheet Center's style with the fixes from the study. Three states:
// before an attempt, a wrong answer, a correct answer. It also checks every
// token pair for contrast and stops if one fails.
// Run: node docs/directions/d-workbench/build.ts
import { writeFileSync } from "node:fs";
import { contrastRatio } from "../../../tools/lib/contrast.ts";
import { PAIRS } from "../tokens.ts";
import { dark, light, panel } from "./tokens.ts";

const OUT = "docs/directions/d-workbench";
type State = "initial" | "wrong" | "correct";

// Contrast first: the build fails rather than write a page that does not pass.
const report = PAIRS.map((p) => {
  const l = contrastRatio(light[p.fg], light[p.bg]);
  const d = contrastRatio(dark[p.fg], dark[p.bg]);
  return { ...p, l, d, ok: l >= p.min && d >= p.min };
});
const failing = report.filter((r) => !r.ok);
if (failing.length) {
  for (const f of failing)
    console.error(`FAIL ${f.fg} on ${f.bg}: ${f.l.toFixed(2)} / ${f.d.toFixed(2)} (min ${f.min})`);
  process.exit(1);
}
writeFileSync(
  `${OUT}/contrast.md`,
  `# Workbench: measured contrast\n\n| Pair | Use | Min | Light | Dark |\n|---|---|---|---|---|\n${report
    .map(
      (r) => `| ${r.fg} on ${r.bg} | ${r.use} | ${r.min} | ${r.l.toFixed(2)} | ${r.d.toFixed(2)} |`,
    )
    .join("\n")}\n`,
);

const keys = Object.keys(light) as (keyof typeof light)[];
writeFileSync(
  `${OUT}/tokens.css`,
  `/* Generated by build.ts from tokens.ts. */
${[400, 500, 600, 700].map((w) => `@font-face {\n  font-family: "Inter";\n  src: url("../fonts/inter-latin-${w}-normal.woff2") format("woff2");\n  font-weight: ${w};\n  font-display: swap;\n}`).join("\n")}
${[400, 600].map((w) => `@font-face {\n  font-family: "IBM Plex Mono";\n  src: url("../fonts/ibm-plex-mono-latin-${w}-normal.woff2") format("woff2");\n  font-weight: ${w};\n  font-display: swap;\n}`).join("\n")}
:root {
  color-scheme: light dark;
  --font-text: "Inter", system-ui, sans-serif;
  --font-mono: "IBM Plex Mono", ui-monospace, monospace;
${keys.map((k) => `  --${k}: light-dark(${light[k]}, ${dark[k]});`).join("\n")}
  --panel: light-dark(${panel.light}, ${panel.dark});
}
`,
);

const ROWS: [string, string][] = [
  ["Month", "Sales"],
  ["Jan", "120"],
  ["Feb", "95"],
  ["Mar", "143"],
  ["Apr", "88"],
  ["Total", ""],
  ...Array.from({ length: 9 }, (): [string, string] => ["", ""]),
];
const READ: Record<State, [number, number] | null> = {
  initial: null,
  wrong: [2, 4],
  correct: [2, 5],
};
const ANSWER: Record<State, string> = { initial: "", wrong: "358", correct: "446" };
const FORMULA: Record<State, string> = {
  initial: "",
  wrong: "=SUM(B2:B4)",
  correct: "=SUM(B2:B5)",
};

function grid(state: State): string {
  const read = READ[state];
  const body = ROWS.map(([a, b], i) => {
    const r = i + 1;
    const inRead = read !== null && r >= read[0] && r <= read[1];
    const answer = r === 6;
    const bClass = [
      /^\d+$/.test(b) || answer ? "num" : "",
      inRead ? "read" : "",
      inRead && r === read?.[0] ? "read-first" : "",
      inRead && r === read?.[1] ? "read-last" : "",
      answer ? `answer answer-${state}` : "",
    ].filter(Boolean);
    const extra = r > 7 ? ' class="extra-row"' : "";
    const rowHead = answer ? ' class="active"' : "";
    const aClass = r === 1 || answer ? ' class="label"' : "";
    return `            <tr${extra}><th scope="row"${rowHead}>${r}</th><td${aClass}>${a}</td><td${bClass.length ? ` class="${bClass.join(" ")}"` : ""}>${answer ? ANSWER[state] : b}</td><td></td><td class="extra-col"></td><td class="extra-col"></td><td class="extra-col"></td></tr>`;
  }).join("\n");
  return `          <table class="grid">
            <caption class="visually-hidden">Sales by month. Your answer goes in B6.</caption>
            <thead><tr><td class="corner"></td><th scope="col">A</th><th scope="col" class="active">B</th><th scope="col">C</th><th scope="col" class="extra-col">D</th><th scope="col" class="extra-col">E</th><th scope="col" class="extra-col">F</th></tr></thead>
            <tbody>
${body}
            </tbody>
          </table>`;
}

function status(state: State): string {
  if (state === "wrong") {
    return `<div class="status status-wrong">
          <div class="verdict" role="status">
            <p><strong>Wrong total in B6.</strong> Your formula gives 358.</p>
            <p>It adds <code class="ref">B2:B4</code>, outlined in blue: 3 cells.</p>
          </div>
          <div class="status-actions">
            <a class="link-button" href="#hints">Show a hint</a>
            <button class="primary" type="submit" form="work">Check</button>
          </div>
        </div>`;
  }
  if (state === "correct") {
    return `<div class="status status-correct">
          <div class="verdict" role="status">
            <p><strong>Correct.</strong> <code>=SUM(B2:B5)</code> adds 4 cells and gives 446.</p>
          </div>
          <div class="status-actions">
            <a class="next" href="/exercises/find-the-average/">Next<span class="next-title">: Find the average</span><span class="arrow" aria-hidden="true">→</span></a>
          </div>
        </div>`;
  }
  return `<div class="status">
          <div class="verdict" role="status">
            <p>Type a formula for B6, then press Enter.</p>
          </div>
          <div class="status-actions">
            <button class="primary" type="submit" form="work">Check</button>
          </div>
        </div>`;
}

function page(state: State): string {
  const title = {
    initial: "Add up a column",
    wrong: "Add up a column (wrong answer)",
    correct: "Add up a column (correct answer)",
  }[state];
  const value = FORMULA[state] ? ` value="${FORMULA[state]}"` : "";
  const nav = ["Exercises", "Functions", "Progress"]
    .map(
      (n) =>
        `<li><a href="/${n.toLowerCase()}/"${n === "Exercises" ? ' aria-current="page"' : ""}>${n}</a></li>`,
    )
    .join("");
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="color-scheme" content="light dark" />
  <title>${title}</title>
  <link rel="stylesheet" href="tokens.css" />
  <link rel="stylesheet" href="style.css" />
</head>
<body class="state-${state}">
  <a class="skip" href="#formula">Skip to the formula</a>
  <header class="site">
    <a class="brand" href="/">Formula Practice</a>
    <nav class="nav-wide" aria-label="Main"><ul>${nav}</ul></nav>
    <button class="menu" type="button" commandfor="menu" command="show-modal">Menu</button>
    <dialog id="menu" aria-label="Menu">
      <nav aria-label="Main"><ul>${nav}</ul></nav>
      <button type="button" commandfor="menu" command="close">Close</button>
    </dialog>
  </header>
  <main id="main" class="exercise">
    <div class="task">
      <nav class="crumbs" aria-label="Breadcrumb"><ol><li><a href="/exercises/">Exercises</a></li><li><a href="/topics/totals/">Totals</a></li></ol></nav>
      <div class="title-row">
        <h1>Add up a column</h1>
        <span class="badge">Beginner</span>
      </div>
      <p class="prompt">In <strong>B6</strong>, add up the sales in <strong>B2</strong> to <strong>B5</strong>.</p>
    </div>
    <section class="work" aria-label="Spreadsheet">
      <div class="sheet">
        <div class="sheet-bar">
          <h2>Sheet</h2>
          <button class="reset" type="button">Reset</button>
        </div>
        <form class="formula-row" id="work" action="/exercises/add-up-a-column/">
          <span class="namebox" aria-hidden="true">B6</span>
          <label class="visually-hidden" for="formula">Formula for B6</label>
          <input class="formula" id="formula" name="formula" type="text"${value} placeholder="=" autocomplete="off" autocapitalize="off" spellcheck="false" />
        </form>
        <div class="grid-wrap">
${grid(state)}
        </div>
      </div>
      ${status(state)}
    </section>
    <div class="details">
      <p class="count">Exercise 1 of 24 in Totals</p>
      <p>Adding up a column is the most common job in a report. SUM does it in one step, and the total updates when a number changes.</p>
      <h2>What you need to do</h2>
      <ol class="steps">
        <li>Type a formula in <strong>B6</strong>.</li>
        <li>Use SUM with the range <strong>B2</strong> to <strong>B5</strong>.</li>
        <li>Press Enter.</li>
      </ol>
      <p class="checks">This exercise checks that you use SUM, point at the cells, and get the right total.</p>
      <h2 id="hints">Need help?</h2>
      <details>
        <summary>Hint 1</summary>
        <p>One function adds a whole range of cells.</p>
      </details>
      <details>
        <summary>Hint 2</summary>
        <p>SUM takes a range written as the first cell, a colon, then the last cell.</p>
      </details>
      <details>
        <summary>Show the answer</summary>
        <p>The answer is <code>=SUM(B2:B5)</code>. Opening this marks the exercise as solved with help.</p>
      </details>
      <h2>Related functions</h2>
      <ul class="chips">
        <li><a href="/functions/sum/">SUM</a></li>
        <li><a href="/functions/average/">AVERAGE</a></li>
        <li><a href="/functions/count/">COUNT</a></li>
        <li><a href="/functions/max/">MAX</a></li>
        <li><a href="/functions/min/">MIN</a></li>
      </ul>
      <p class="back"><a href="/exercises/">All exercises</a></p>
    </div>
  </main>
  <footer class="site">
    <ul>
      <li><a href="/exercises/">Exercises</a></li>
      <li><a href="/functions/">Functions</a></li>
      <li><a href="/progress/">Progress</a></li>
      <li><a href="/privacy/">Privacy</a></li>
      <li><a href="/contact/">Contact</a></li>
    </ul>
  </footer>
</body>
</html>
`;
}

for (const s of ["initial", "wrong", "correct"] as const)
  writeFileSync(`${OUT}/exercise-${s}.html`, page(s));
console.log("Wrote Workbench mocks. All contrast pairs pass.");
