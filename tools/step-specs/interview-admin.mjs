// Row 0 gets extra headers or inputs in columns D:F (index 3 to 5).
const withInputs = (rows, extra) => {
  const width = Math.max(
    ...rows.map((r) => r.length),
    ...Object.values(extra).map((e) => 3 + e.length),
  );
  return rows.map((r, i) =>
    Array.from({ length: width }, (_, j) =>
      extra[i] && j >= 3 && j - 3 < extra[i].length ? extra[i][j - 3] : (r[j] ?? null),
    ),
  );
};

