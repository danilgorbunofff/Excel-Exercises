// Why this exists: measures the web fonts against the local fonts the browser
// shows before they load, and writes @font-face overrides that make the two
// take the same space. A font swap then moves nothing on the page. Run it again
// whenever a font file changes: node tools/font-metrics.ts
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const PAIRS = [
  {
    family: "Inter",
    file: "public/fonts/inter-latin-400-normal.woff2",
    fallbackName: "Inter Fallback",
    local: "Arial",
  },
  {
    family: "IBM Plex Mono",
    file: "public/fonts/ibm-plex-mono-latin-400-normal.woff2",
    fallbackName: "IBM Plex Mono Fallback",
    local: "Courier New",
  },
] as const;

/** Letters weighted roughly like English text, plus the digits and signs used in formulas. */
const SAMPLE =
  "The quick brown fox jumps over the lazy dog. Add up the sales in B2 to B5, then press Enter. =SUM(B2:B5) 0123456789";
const PARAGRAPH =
  "In B8, count the invoices for more than 100. An invoice for exactly 100 does not count. Put the condition in double quotes, operator included, as in the example.";

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent("<!doctype html><title>metrics</title><body></body>");

const percent = (n: number) => `${(n * 100).toFixed(2)}%`;
const blocks: string[] = [];
const report: string[] = [];

for (const pair of PAIRS) {
  const data = readFileSync(pair.file).toString("base64");
  const m = await page.evaluate(
    async ({ family, data, local, sample }) => {
      const face = new FontFace(family, `url(data:font/woff2;base64,${data})`);
      document.fonts.add(await face.load());
      const ctx = document.createElement("canvas").getContext("2d");
      if (!ctx) throw new Error("no canvas");
      const measure = (font: string) => {
        ctx.font = `100px ${font}`;
        const t = ctx.measureText(sample);
        return {
          width: t.width,
          ascent: t.fontBoundingBoxAscent,
          descent: t.fontBoundingBoxDescent,
        };
      };
      return { web: measure(`"${family}"`), local: measure(`"${local}"`) };
    },
    { family: pair.family, data, local: pair.local, sample: SAMPLE },
  );
  const sizeAdjust = m.web.width / m.local.width;
  // Overrides are scaled by size-adjust, so they are divided by it here.
  const ascent = m.web.ascent / 100 / sizeAdjust;
  const descent = m.web.descent / 100 / sizeAdjust;
  blocks.push(
    [
      "@font-face {",
      `  font-family: "${pair.fallbackName}";`,
      `  src: local("${pair.local}");`,
      `  size-adjust: ${percent(sizeAdjust)};`,
      `  ascent-override: ${percent(ascent)};`,
      `  descent-override: ${percent(descent)};`,
      "  line-gap-override: 0%;",
      "}",
    ].join("\n"),
  );
  report.push(`${pair.family} against ${pair.local}: size-adjust ${percent(sizeAdjust)}`);
}

const css = `/* Generated by tools/font-metrics.ts. Do not edit by hand.
   Local fonts resized to take the same space as the web fonts, so the page
   does not move when the web fonts arrive. */
${blocks.join("\n")}
`;
writeFileSync("src/styles/font-fallbacks.css", css);

// Check: the same paragraph in the web font and in the tuned fallback.
for (const pair of PAIRS) {
  const data = readFileSync(pair.file).toString("base64");
  const sizes = await page.evaluate(
    async ({ css, family, fallbackName, data, text }) => {
      const face = new FontFace(family, `url(data:font/woff2;base64,${data})`);
      document.fonts.add(await face.load());
      const style = document.createElement("style");
      style.textContent = css;
      document.head.append(style);
      await document.fonts.ready;
      const box = (font: string) => {
        const p = document.createElement("p");
        p.style.cssText = `width:320px;font:16px/1.5 ${font};margin:0`;
        p.textContent = text;
        document.body.append(p);
        const r = p.getBoundingClientRect();
        const lastLine = p.getClientRects()[0];
        p.remove();
        return { height: r.height, lastLine: lastLine?.width ?? 0 };
      };
      return { web: box(`"${family}"`), fallback: box(`"${fallbackName}"`) };
    },
    { css, family: pair.family, fallbackName: pair.fallbackName, data, text: PARAGRAPH },
  );
  report.push(
    `${pair.family}: paragraph at 320 px is ${sizes.web.height} px high in the web font and ${sizes.fallback.height} px in the fallback.`,
  );
}

await browser.close();
console.log(report.join("\n"));
